def render_markup(text: str) -> str:
    """Tiny formatter for lesson text: paragraphs, '- ' bullets, **bold**. Input is our own trusted content."""
    import html

    out, bullets = [], []

    def flush() -> None:
        if bullets:
            out.append("<ul>" + "".join(f"<li>{b}</li>" for b in bullets) + "</ul>")
            bullets.clear()

    for block in text.strip().split("\n"):
        line = html.escape(block.strip())
        line = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
        if not line:
            flush()
            continue
        if line.startswith("- "):
            bullets.append(line[2:])
        else:
            flush()
            out.append(f"<p>{line}</p>")
    flush()
    return "\n".join(out)


def seed_learning(db: Database) -> None:
    """Insert lessons and starter glossary entries that are missing (never overwrites your edits)."""
    with db.session() as s:
        have_concepts = set(s.scalars(select(Concept.slug)))
        for slug, name, cat in SEED_CONCEPTS:
            if slug not in have_concepts:
                s.add(Concept(slug=slug, name=name, category=cat, related_concepts=[], origin="seed", created_at=utcnow()))
        s.flush()
        slug_to_id = dict(s.execute(select(Concept.slug, Concept.id)).all())
        have_lessons = {l.title: l for l in s.scalars(select(Lesson))}
        for order, (path, key, title, symbols, slugs, content) in enumerate(LESSONS):
            if title in have_lessons:
                continue
            s.add(Lesson(path=path, sort_order=order, title=title, content=content.strip(),
                         concept_ids=[slug_to_id[x] for x in slugs if x in slug_to_id]))


LESSON_META = {title: (key, symbols, slugs) for _, key, title, symbols, slugs, _ in LESSONS}


class LearningService:
    def __init__(self, db: Database, gemini: GeminiService, news) -> None:  # noqa: ANN001
        self.db = db
        self.gemini = gemini
        self.news = news

    # ================================================================== glossary
    def concepts(self, q: str | None = None, category: str | None = None) -> list[dict[str, Any]]:
        with self.db.session() as s:
            stmt = select(Concept).order_by(func.lower(Concept.name))
            if q:
                like = f"%{q}%"
                stmt = stmt.where((Concept.name.ilike(like)) | (Concept.short_definition.ilike(like)))
            if category:
                stmt = stmt.where(Concept.category == category)
            rows = s.scalars(stmt).all()
            prog = {p.concept_id: p for p in s.scalars(select(ConceptProgress))}
            return [{"slug": c.slug, "name": c.name, "category": c.category or "general", "short": c.short_definition,
                     "explained": bool(c.long_explanation), "times_seen": prog[c.id].times_seen if c.id in prog else 0,
                     "mastery": prog[c.id].mastery_level if c.id in prog else None} for c in rows]

    def concept(self, slug: str) -> dict[str, Any] | None:
        with self.db.session() as s:
            c = s.scalar(select(Concept).where(Concept.slug == slug))
            if c is None:
                return None
            p = s.get(ConceptProgress, c.id)
            related = [{"slug": r.slug, "name": r.name} for r in s.scalars(select(Concept).where(Concept.slug.in_(c.related_concepts or [])))]
            return {"id": c.id, "slug": c.slug, "name": c.name, "category": c.category or "general", "short": c.short_definition,
                    "long": c.long_explanation, "example": c.example, "related": related, "related_raw": c.related_concepts or [],
                    "origin": c.origin, "updated_at": c.updated_at.isoformat() if c.updated_at else None,
                    "times_seen": p.times_seen if p else 0, "mastery": p.mastery_level if p else None}

    def mark_seen(self, slugs: list[str]) -> None:
        if not slugs:
            return
        with self.db.session() as s:
            for c in s.scalars(select(Concept).where(Concept.slug.in_(slugs))):
                p = s.get(ConceptProgress, c.id) or ConceptProgress(concept_id=c.id, times_seen=0, mastery_level=0.0)
                p.times_seen = (p.times_seen or 0) + 1
                p.last_seen = utcnow()
                s.merge(p)

    def articles_for_concept(self, slug: str, name: str, limit: int = 8) -> list[dict[str, Any]]:
        """Stored articles whose breakdown lists this concept, plus recent headlines mentioning its name."""
        ids: list[int] = []
        with self.db.session() as s:
            for b in s.scalars(select(Breakdown).order_by(Breakdown.created_at.desc()).limit(400)):
                if any(c.get("slug") == slug for c in (b.json_content or {}).get("concepts", [])):
                    ids.append(b.article_id)
            core = re.sub(r"\(.*?\)", "", name).strip()
            if len(core) >= 3:
                ids += list(s.scalars(select(NewsArticle.id).where(NewsArticle.title.ilike(f"%{core}%"))
                                      .order_by(NewsArticle.fetched_at.desc()).limit(limit)))
        ids = list(dict.fromkeys(ids))[:limit]
        return self.news.query(ids=ids, hours=None, limit=limit) if ids else []

    def explain_concept(self, slug: str) -> dict[str, Any]:
        """Generate the full explanation once (blocking). Examples come only from stored news."""
        c = self.concept(slug)
        if c is None:
            raise AIError("Unknown concept")
        examples = self.articles_for_concept(slug, c["name"], limit=5)
        ex_text = "\n".join(f"- [{a['source_name']}] {a['title']}" + (f" — {(a.get('description') or '')[:200]}" if a.get("description") else "")
                            for a in examples) or "(no stored news mentions this concept yet)"
        lesson_text = ""
        with self.db.session() as s:
            for l in s.scalars(select(Lesson)):
                if c["id"] in (l.concept_ids or []):
                    lesson_text += f"\nLesson '{l.title}':\n{l.content[:1500]}\n"
        known = [x["slug"] for x in self.concepts()][:200]
        prompt = f"""Explain this market concept for a beginner-to-intermediate learner.

CONCEPT: {c['name']} (slug: {c['slug']})
EXISTING SHORT DEFINITION: {c['short'] or '(none)'}
RELATED LESSON TEXT FROM THIS APP:{lesson_text or ' (none)'}
RECENT REAL NEWS HEADLINES (use one as the real-world example if it fits; otherwise write 'Not enough information.'):
{ex_text}
OTHER CONCEPTS IN THE GLOSSARY (pick related_concepts only from these slugs): {', '.join(known)}

Write JSON: name, category, short_definition (one sentence), long_explanation (one or two short paragraphs,
cause and effect, simple words), example (refer to one of the headlines above by source and topic), related_concepts (slugs).
Do not include any specific numbers, prices, percentages or dates unless they appear above."""
        out, passed, notes, model = generate_validated(self.gemini, "concept_explanation", prompt, ConceptExplanation, tier="smart",
                                                       skip_keys=("category", "related_concepts"))
        data = out.model_dump()
        rel = [slugify(x) for x in data["related_concepts"] if slugify(x) in set(known) and slugify(x) != slug][:8]
        with self.db.session() as s:
            row = s.scalar(select(Concept).where(Concept.slug == slug))
            row.short_definition = data["short_definition"]
            row.long_explanation = data["long_explanation"]
            row.example = data["example"]
            row.category = row.category or data["category"]
            row.related_concepts = rel
            row.origin = "ai"
            row.updated_at = utcnow()
        if not passed:
            log.warning("Concept %s explanation: %s", slug, notes)
        return self.concept(slug)  # type: ignore[return-value]

    def edit_concept(self, slug: str, short: str, long: str, example: str) -> None:
        with self.db.session() as s:
            row = s.scalar(select(Concept).where(Concept.slug == slug))
            if row is None:
                raise KeyError(slug)
            row.short_definition, row.long_explanation, row.example = short.strip(), long.strip(), example.strip()
            row.origin, row.updated_at = "edited", utcnow()

    # ================================================================== lessons
    def paths(self) -> list[dict[str, Any]]:
        with self.db.session() as s:
            done = set(s.scalars(select(LessonProgress.lesson_id)))
            lessons = s.scalars(select(Lesson).order_by(Lesson.sort_order)).all()
            out = []
            for key, title, desc in PATHS:
                ls = [{"id": l.id, "title": l.title, "done": l.id in done} for l in lessons if l.path == key]
                out.append({"key": key, "title": title, "description": desc, "lessons": ls,
                            "done": sum(1 for x in ls if x["done"]), "total": len(ls)})
            return out

    def lesson(self, lesson_id: int) -> dict[str, Any] | None:
        with self.db.session() as s:
            l = s.get(Lesson, lesson_id)
            if l is None:
                return None
            concepts = [{"slug": c.slug, "name": c.name, "short": c.short_definition}
                        for c in s.scalars(select(Concept).where(Concept.id.in_(l.concept_ids or [])))]
            done = s.get(LessonProgress, l.id) is not None
            siblings = s.scalars(select(Lesson).where(Lesson.path == l.path).order_by(Lesson.sort_order)).all()
        key, symbols, _ = LESSON_META.get(l.title, ("", [], []))
        idx = [x.id for x in siblings].index(l.id)
        return {"id": l.id, "path": l.path, "title": l.title, "html": render_markup(l.content), "content": l.content,
                "concepts": concepts, "done": done, "symbols": symbols,
                "prev": siblings[idx - 1].id if idx > 0 else None, "next": siblings[idx + 1].id if idx + 1 < len(siblings) else None,
                "path_title": dict((p[0], p[1]) for p in PATHS).get(l.path, l.path)}

    def complete_lesson(self, lesson_id: int, done: bool = True) -> None:
        with self.db.session() as s:
            row = s.get(LessonProgress, lesson_id)
            if done and row is None:
                s.add(LessonProgress(lesson_id=lesson_id, completed_at=utcnow()))
            elif not done and row is not None:
                s.delete(row)

    # ================================================================== quiz generation
    def _source_text(self, source_type: str, source_id: int | str) -> tuple[str, list[str], int | None]:
        """(source text, concept slugs, numeric source id)."""
        with self.db.session() as s:
            if source_type == "article":
                a = s.get(NewsArticle, int(source_id))
                if a is None:
                    raise AIError("Article not found")
                text = f"HEADLINE: {a.title}\n"
                if a.body_fetched and a.body_text:
                    text += f"ARTICLE TEXT:\n{a.body_text[:7000]}"
                else:
                    text += f"DESCRIPTION: {a.description or ''}"
                b = s.scalars(select(Breakdown).where(Breakdown.article_id == a.id).order_by(Breakdown.created_at.desc())).first()
                slugs = [c["slug"] for c in (b.json_content.get("concepts", []) if b else [])]
                if len(text) < 150:
                    raise AIError("This article has too little text to build a fair quiz (only a short headline is available).")
                return text, slugs, a.id
            if source_type == "concept":
                c = s.scalar(select(Concept).where(Concept.slug == str(source_id)))
                if c is None:
                    raise AIError("Concept not found")
                if not c.long_explanation:
                    raise AIError("This concept has no explanation yet. Open it in the glossary and click 'Explain' first.")
                return (f"CONCEPT: {c.name}\nDEFINITION: {c.short_definition}\nEXPLANATION: {c.long_explanation}\nEXAMPLE: {c.example or ''}",
                        [c.slug], c.id)
            if source_type == "lesson":
                l = s.get(Lesson, int(source_id))
                if l is None:
                    raise AIError("Lesson not found")
                slugs = list(s.scalars(select(Concept.slug).where(Concept.id.in_(l.concept_ids or []))))
                return f"LESSON: {l.title}\n{l.content}", slugs, l.id
        raise AIError("Unknown quiz source")

    def generate_quiz(self, source_type: str, source_id: int | str, n: int = 3) -> dict[str, Any]:
        """Generate questions, check them with a second call, store the ones that pass. Blocking."""
        text, slugs, sid = self._source_text(source_type, source_id)
        kind = ("Questions must be answerable ONLY from the source text (facts it reports)." if source_type == "article"
                else "Test understanding: definitions, cause and effect, and 'what would likely happen if...' questions, "
                     "all answerable from the source text.")
        prompt = f"""Write {n} multiple-choice quiz questions for a learner.

SOURCE TEXT:
{text}

Rules:
- {kind}
- 4 options each, exactly one correct; correct_index is 0-3. Make wrong options plausible but clearly wrong per the text.
- explanation: why the correct answer is right (from the text). option_explanations: one short reason per option.
- concept_slugs: choose from {slugs or ['(none)']} where relevant.
- Do not use any number that is not in the source text. No investment advice."""
        qs, passed, notes, model = generate_validated(self.gemini, f"quiz_{source_type}", prompt, QuizSet, tier="smart",
                                                      skip_keys=("concept_slugs", "difficulty"))
        questions = [q for q in qs.questions if len(q.options) == 4 and 0 <= q.correct_index <= 3]  # type: ignore[attr-defined]
        if not questions:
            raise AIError("Gemini returned no usable questions.")
        # ---- checker: answer each question from the source without the key
        listing = "\n".join(f"Q{i}: {q.question}\n" + "\n".join(f"  {j}) {o}" for j, o in enumerate(q.options))
                            for i, q in enumerate(questions))
        check_prompt = f"""You are checking quiz questions against a source text.

SOURCE TEXT:
{text}

QUESTIONS:
{listing}

For each question index (0-based), answer it using ONLY the source text: set correct_index_according_to_source
(0-3, or -1 if the text does not support any single option) and answer_supported_by_source (true only if the
text clearly supports exactly one option). Give a short reason."""
        check = self.gemini.generate(f"quiz_check_{source_type}", check_prompt, tier="fast", schema=CheckResult, temperature=0.0)
        verdicts = {v.index: v for v in check.parsed.verdicts}  # type: ignore[union-attr]
        allowed = allowed_numbers(text)
        kept, dropped = [], []
        for i, q in enumerate(questions):
            v = verdicts.get(i)
            ok = v is not None and v.answer_supported_by_source and v.correct_index_according_to_source == q.correct_index
            ok = ok and not find_invalid(q.model_dump(), allowed, ("concept_slugs", "difficulty", "correct_index"))
            (kept if ok else dropped).append(q)
        with self.db.session() as s:
            for q in kept:
                s.add(QuizQuestion(source_type=source_type, source_id=sid, question=q.question, options=q.options,
                                   correct_index=q.correct_index, explanation=q.explanation,
                                   option_explanations=q.option_explanations, difficulty=q.difficulty,
                                   concept_slugs=[x for x in q.concept_slugs if x in slugs] or slugs[:2],
                                   checker_passed=True, created_at=utcnow()))
        log.info("Quiz from %s %s: %d kept, %d discarded by the checker", source_type, source_id, len(kept), len(dropped))
        return {"kept": len(kept), "discarded": len(dropped), "validation_notes": notes}

    # ================================================================== quiz taking
    def _q_out(self, q: QuizQuestion, s) -> dict[str, Any]:  # noqa: ANN001
        src = None
        if q.source_type == "article" and q.source_id:
            a = s.get(NewsArticle, q.source_id)
            if a:
                src = {"type": "article", "id": a.id, "title": a.title, "url": a.original_url or a.url, "source_name": a.source_name}
        elif q.source_type == "lesson" and q.source_id:
            l = s.get(Lesson, q.source_id)
            if l:
                src = {"type": "lesson", "id": l.id, "title": l.title}
        elif q.source_type == "concept" and q.source_id:
            c = s.get(Concept, q.source_id)
            if c:
                src = {"type": "concept", "slug": c.slug, "title": c.name}
        return {"id": q.id, "question": q.question, "options": q.options, "difficulty": q.difficulty,
                "concepts": q.concept_slugs, "source": src}

    def next_questions(self, mode: str, limit: int = 10) -> list[dict[str, Any]]:
        now = utcnow()
        with self.db.session() as s:
            answered = select(QuizAttempt.question_id)
            if mode == "review":
                ids = list(s.scalars(select(ReviewSchedule.question_id).where(ReviewSchedule.next_review_at <= now)
                                     .order_by(ReviewSchedule.next_review_at).limit(limit)))
                qs = [s.get(QuizQuestion, i) for i in ids]
            elif mode == "today":
                qs = list(s.scalars(select(QuizQuestion).where(QuizQuestion.source_type == "article",
                                                               QuizQuestion.created_at >= now - timedelta(hours=36),
                                                               QuizQuestion.id.not_in(answered))
                                    .order_by(QuizQuestion.created_at.desc()).limit(limit)))
            elif mode == "weak":
                weak = [w["slug"] for w in self.weak_topics(5)]
                pool = list(s.scalars(select(QuizQuestion).where(QuizQuestion.checker_passed.is_(True))))
                qs = [q for q in pool if set(q.concept_slugs or []) & set(weak)]
                random.shuffle(qs)
                qs = qs[:limit]
            else:  # concepts
                qs = list(s.scalars(select(QuizQuestion).where(QuizQuestion.source_type.in_(["concept", "lesson"]),
                                                               QuizQuestion.id.not_in(answered)).limit(limit)))
            return [self._q_out(q, s) for q in qs if q is not None]

    def answer(self, question_id: int, chosen: int) -> dict[str, Any]:
        now = utcnow()
        with self.db.session() as s:
            q = s.get(QuizQuestion, question_id)
            if q is None:
                raise KeyError(question_id)
            correct = chosen == q.correct_index
            s.add(QuizAttempt(question_id=q.id, chosen_index=chosen, correct=correct, answered_at=now))
            row = s.get(ReviewSchedule, q.id)
            state = srs.SrsState(row.repetitions, row.interval_days, row.ease) if row else srs.SrsState()
            new, due = srs.review(state, correct, now)
            if row is None:
                row = ReviewSchedule(question_id=q.id, next_review_at=due)
                s.add(row)
            row.repetitions, row.interval_days, row.ease, row.next_review_at, row.last_reviewed_at = (
                new.repetitions, new.interval_days, new.ease, due, now)
            s.flush()
            self._update_mastery(s, q.concept_slugs or [])
            out = self._q_out(q, s)
        out.update({"correct": correct, "correct_index": q.correct_index, "explanation": q.explanation,
                    "option_explanations": q.option_explanations, "next_review_at": due.isoformat(), "chosen": chosen})
        return out

    def _update_mastery(self, s, slugs: list[str]) -> None:  # noqa: ANN001
        """Mastery = share of correct answers on that concept's questions (last 20 attempts)."""
        for c in s.scalars(select(Concept).where(Concept.slug.in_(slugs))):
            attempts = []
            for q in s.scalars(select(QuizQuestion)):
                if c.slug in (q.concept_slugs or []):
                    attempts += list(s.scalars(select(QuizAttempt.correct).where(QuizAttempt.question_id == q.id)))
            recent = attempts[-20:]
            p = s.get(ConceptProgress, c.id) or ConceptProgress(concept_id=c.id, times_seen=0, mastery_level=0.0)
            p.mastery_level = round(sum(recent) / len(recent), 2) if recent else 0.0
            p.last_seen = utcnow()
            s.merge(p)

    def weak_topics(self, n: int = 5) -> list[dict[str, Any]]:
        stats: dict[str, list[bool]] = {}
        with self.db.session() as s:
            qmap = {q.id: q.concept_slugs or [] for q in s.scalars(select(QuizQuestion))}
            for qid, correct in s.execute(select(QuizAttempt.question_id, QuizAttempt.correct)):
                for slug in qmap.get(qid, []):
                    stats.setdefault(slug, []).append(bool(correct))
            names = dict(s.execute(select(Concept.slug, Concept.name)).all())
        rows = [{"slug": k, "name": names.get(k, k), "attempts": len(v), "accuracy": sum(v) / len(v)}
                for k, v in stats.items() if len(v) >= 2]
        rows.sort(key=lambda r: (r["accuracy"], -r["attempts"]))
        return rows[:n]

    def stats(self) -> dict[str, Any]:
        now = utcnow()
        with self.db.session() as s:
            attempts = s.execute(select(QuizAttempt.answered_at, QuizAttempt.correct).order_by(QuizAttempt.answered_at)).all()
            due = s.scalar(select(func.count()).select_from(ReviewSchedule).where(ReviewSchedule.next_review_at <= now)) or 0
            total_q = s.scalar(select(func.count()).select_from(QuizQuestion)) or 0
            lessons_done = s.scalar(select(func.count()).select_from(LessonProgress)) or 0
            lessons_total = s.scalar(select(func.count()).select_from(Lesson)) or 0
        by_day: dict[str, list[bool]] = {}
        for at, correct in attempts:
            by_day.setdefault(at.astimezone(JAKARTA).date().isoformat(), []).append(bool(correct))
        history = [{"date": d, "answered": len(v), "correct": sum(v)} for d, v in sorted(by_day.items())][-14:]
        return {"answered": len(attempts), "correct": sum(1 for _, c in attempts if c), "due": due, "questions": total_q,
                "history": history, "weak": self.weak_topics(), "lessons_done": lessons_done, "lessons_total": lessons_total}

    def pool(self) -> list[dict[str, Any]]:
        """Every checked quiz question with its answer key (for the website, where answers are checked in the browser)."""
        with self.db.session() as s:
            out = []
            for q in s.scalars(select(QuizQuestion).where(QuizQuestion.checker_passed.is_(True)).order_by(QuizQuestion.id)):
                d = self._q_out(q, s)
                d.update({"correct_index": q.correct_index, "explanation": q.explanation,
                          "option_explanations": q.option_explanations, "source_type": q.source_type,
                          "created_at": q.created_at.isoformat()})
                out.append(d)
            return out

    def review_sample(self, n: int = 3) -> list[dict[str, Any]]:
        qs = self.next_questions("review", n)
        if len(qs) < n:
            with self.db.session() as s:
                extra = list(s.scalars(select(QuizQuestion).order_by(QuizQuestion.created_at.desc()).limit(n * 3)))
                seen = {q["id"] for q in qs}
                for q in extra:
                    if q.id not in seen and len(qs) < n:
                        qs.append(self._q_out(q, s))
        return qs


